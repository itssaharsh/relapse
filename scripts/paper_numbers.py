"""Writes the paper's numbers and tables from the result files, so nothing in the paper is typed by hand.

    python scripts/paper_numbers.py
Creates paper/numbers.tex, paper/table_control.tex and paper/table_map.tex.
"""
from __future__ import annotations

import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAPER = os.path.join(ROOT, "paper")
WINDOWS = ("3-5", "5-7", "7-9", "10-12", "13-15")


def signed(x: float, d: int = 1) -> str:
    x = round(x, d) + 0.0
    return f"$-${abs(x):.{d}f}" if x < 0 else f"+{x:.{d}f}"


def control() -> tuple[str, dict]:
    rows = json.load(open(os.path.join(ROOT, "results", "correct_tokenizer", "tokenizer_control.json")))
    get = lambda m, t: next(100 * r["wmdp-bio"] for r in rows if r["model"] == m and r["tokenizer"] == t)
    names = (("base", "Original"), ("rmu_default_layers", "RMU, layers 5--7"), ("rmu_circuit_layers", "RMU, layers 7--9"), ("rmu_deeper", "RMU, layers 10--12"))
    body = "".join(f"{label} & {get(m, 'kaggle_copy'):.1f} & {get(m, 'current_official'):.1f} & {signed(get(m, 'current_official') - get(m, 'kaggle_copy'))} \\\\\n" for m, label in names)
    tex = ("\\begin{table}[t]\n\\centering\\small\n\\begin{tabular}{lrrr}\n\\toprule\n"
           "Same weights & Outdated & Official & Change \\\\\n\\midrule\n" + body +
           "\\bottomrule\n\\end{tabular}\n\\caption{\\wmdp{} accuracy (\\%) of the same weights on Global, scored in one job through each tokenizer setting. The weights were trained through the outdated setting. Lower is better.}\n\\label{tab:control}\n\\end{table}\n")
    return tex, {"ctlMaxRise": f"{max(get(m, 'current_official') - get(m, 'kaggle_copy') for m, _ in names):.1f}"}


def relapse_map() -> tuple[str, dict]:
    m = json.load(open(os.path.join(ROOT, "results", "map", "summary.json")))
    eff = [r for r in m["runs"] if r["effective"]]
    count = lambda rs, f: sum(bool(r.get(f, {}).get("relapse")) for r in rs)
    body = ""
    for w in WINDOWS:
        rs = [r for r in eff if r["window"] == w]
        body += f"{w.replace('-', '--')} & {len(rs)} & {count(rs, 'Q4_0')} & {count(rs, 'nf4')} \\\\\n"
    body += f"\\midrule\nAll & {len(eff)} & {count(eff, 'Q4_0')} & {count(eff, 'nf4')} \\\\\n"
    tex = ("\\begin{table}[t]\n\\centering\\small\n\\begin{tabular}{lrrr}\n\\toprule\n"
           "Layers & Effective runs & \\fq{} relapses & \\nf{} relapses \\\\\n\\midrule\n" + body +
           "\\bottomrule\n\\end{tabular}\n\\caption{The pre-registered map, through the official tokenizer. A relapse is a rise of at least 5 points over fp16 with paired $p<0.05$.}\n\\label{tab:map}\n\\end{table}\n")
    delta = lambda f: np.array([100 * r[f]["delta"] for r in eff])
    rel = [(r, f) for r in eff for f in ("Q4_0", "nf4") if r[f]["relapse"]]
    h = m["all_five"]; ho = m["held_out"]
    nums = {"mapRuns": len(m["runs"]), "mapEffective": len(eff), "mapHeld": len(eff) - len({id(r) for r, _ in rel}), "mapRelapses": len(rel),
            "mapMeanQ": signed(delta("Q4_0").mean()), "mapMeanN": signed(delta("nf4").mean()),
            "mapRelapseLow": f"{min(100 * r[f]['delta'] for r, f in rel):.1f}", "mapRelapseHigh": f"{max(100 * r[f]['delta'] for r, f in rel):.1f}",
            "mapHfourA": f"{h['H4']['10_12'][0]} of {h['H4']['10_12'][1]}", "mapHfourB": f"{h['H4']['7_9'][0]} of {h['H4']['7_9'][1]}", "mapHfourP": f"{h['H4']['p']:.3f}",
            "mapHeldHfourA": f"{ho['H4']['10_12'][0]} of {ho['H4']['10_12'][1]}", "mapHeldHfourB": f"{ho['H4']['7_9'][0]} of {ho['H4']['7_9'][1]}", "mapHeldHfourP": f"{ho['H4']['p']:.2f}",
            "mapHthreeN": h["H3"]["not_comparable"]}
    return tex, nums


def main() -> None:
    t1, n1 = control(); t2, n2 = relapse_map()
    open(os.path.join(PAPER, "table_control.tex"), "w").write(t1)
    open(os.path.join(PAPER, "table_map.tex"), "w").write(t2)
    open(os.path.join(PAPER, "numbers.tex"), "w").write("% generated by scripts/paper_numbers.py\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in {**n1, **n2}.items()))


if __name__ == "__main__":
    main()
